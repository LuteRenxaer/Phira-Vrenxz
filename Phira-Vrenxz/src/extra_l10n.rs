fn current_lang() -> &'static str {
    let order = prpr_l10n::GLOBAL.order.lock().unwrap();
    let idx = order.first().copied().unwrap_or(0);
    prpr_l10n::LANGS.get(idx).copied().unwrap_or("en-US")
}

