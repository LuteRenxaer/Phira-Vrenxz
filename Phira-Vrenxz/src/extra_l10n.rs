/// Translate a legacy hardcoded Chinese UI string.
/// zh-CN keeps the source; zh-TW uses traditional; ja/ko have their own tables.
pub fn tr(s: &'static str) -> &'static str {
    match current_lang() {
        "zh-CN" => s,
        "zh-TW" => tw_map().get(s).copied().unwrap_or(s),
        "ja-JP" => ja_map().get(s).copied().unwrap_or(s),
        "ko-KR" => ko_map().get(s).copied().unwrap_or(s),
        _ => en_map().get(s).copied().unwrap_or(s),
    }
}

#[macro_export]
macro_rules! tr {
    ($s:literal) => { $crate::extra_l10n::tr($s) };
}
